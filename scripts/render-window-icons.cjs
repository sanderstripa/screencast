// Exact CONNECT window buttons: Lucide 15px SVG, centered in a 28x30px box.
// npm install playwright@1.56.1 pngjs@7.0.0 (or use an existing NODE_PATH).
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const {chromium}=require('playwright'),{PNG}=require('pngjs');
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const lines=['// Generated by scripts/render-window-icons.cjs from unchanged CONNECT SVGs.','#pragma once','namespace vpnWindowPixels {','struct Mask { int width,height; unsigned char const* alpha; };'];
 for(const name of ['minus','x']){
  const svg=fs.readFileSync(path.join(root,'assets/connect-ui',name+'.svg'),'utf8');
  lines.push('// '+name+' source SHA256 '+crypto.createHash('sha256').update(svg.replace(/\r\n/g,'\n')).digest('hex'));
  const dimensions={};
  for(const dpi of [96,120,144,168,192,240,288,384]){
   const page=await browser.newPage({viewport:{width:64,height:64},deviceScaleFactor:dpi/96});
   await page.setContent('<style>html,body{margin:0;background:transparent}#button{width:28px;height:30px;display:grid;place-items:center;color:white}svg{width:15px;height:15px;display:block}</style><div id="button">'+svg+'</div>');
   const png=await page.locator('#button').screenshot({omitBackground:true,animations:'disabled'}),decoded=PNG.sync.read(png),alpha=[];
   dimensions[dpi]=[decoded.width,decoded.height];
   for(let i=3;i<decoded.data.length;i+=4)alpha.push(decoded.data[i]);
   fs.writeFileSync(path.join(root,'assets/connect-ui',name+'-button-browser-'+dpi+'.png'),png);
   lines.push('inline constexpr unsigned char '+name+dpi+'[]={'+alpha.join(',')+'};');
   await page.close();
  }
  lines.push('inline Mask '+name+'(int dpi){switch(dpi){');
  for(const [dpi,[w,h]] of Object.entries(dimensions))lines.push('case '+dpi+':return {'+w+','+h+','+name+dpi+'};');
  lines.push('default:return {28,30,'+name+'96};}}');
 }
 lines.push('}');fs.writeFileSync(path.join(root,'src/vpn_window_pixels.h'),lines.join('\n')+'\n');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
