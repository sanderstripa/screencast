// Render CONNECT's unchanged Lucide SVGs with Chromium, as in its WebView UI.
// NODE_PATH may point to an existing installation of playwright and pngjs.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const {chromium}=require('playwright'),{PNG}=require('pngjs');
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:64,height:64},deviceScaleFactor:1});
 const lines=['// Generated by scripts/render-theme-icons.cjs from CONNECT SVGs using Chromium.','#pragma once','namespace vpnThemePixels {','struct Mask { int size; unsigned char const* alpha; };'];
 for(const name of ['monitor','sun','moon']){
  const svg=fs.readFileSync(path.join(root,'assets/connect-ui',name+'.svg'),'utf8');
  lines.push('// '+name+' source SHA256 '+crypto.createHash('sha256').update(svg.replace(/\r\n/g,'\n')).digest('hex'));
  for(let size=13;size<=52;size++){
   await page.setContent('<style>html,body{margin:0;background:transparent}svg{display:block;color:white;width:'+size+'px;height:'+size+'px}</style>'+svg);
   const png=await page.locator('svg').screenshot({omitBackground:true,animations:'disabled'});
   const decoded=PNG.sync.read(png),alpha=[];
   for(let i=3;i<decoded.data.length;i+=4)alpha.push(decoded.data[i]);
   if(size===13)fs.writeFileSync(path.join(root,'assets/connect-ui',name+'-browser-13.png'),png);
   lines.push('inline constexpr unsigned char '+name+size+'[]={'+alpha.join(',')+'};');
  }
  lines.push('inline Mask '+name+'(int size){switch(size){');
  for(let size=13;size<=52;size++)lines.push('case '+size+':return {'+size+','+name+size+'};');
  lines.push('default:return {13,'+name+'13};}}');
 }
 lines.push('}');fs.writeFileSync(path.join(root,'src/vpn_theme_pixels.h'),lines.join('\n')+'\n');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
